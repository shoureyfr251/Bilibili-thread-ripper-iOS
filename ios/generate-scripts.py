"""Generate compiled-in JS sources with provenance; no external IPA resource."""
import hashlib
import json
from pathlib import Path

base = Path(__file__).resolve().parent
sources = {"BTRCoreScript": base.parent / "src/range-core.js",
           "BTRPolicyScript": base / "policy.js", "BTRHTTPScript": base / "loopback-http.js",
           # Desktop engine: unmodified stable copies (js/desktop/SOURCE.txt) plus iOS shims/glue.
           "BTREngineRangeCoreScript": base / "js/desktop/range-core.js",
           "BTREngineShimScript": base / "js/shims.js",
           "BTREnginePreludeScript": base / "js/engine-prelude.js",
           "BTREngineResolverScript": base / "js/desktop/cdn-resolver.js",
           "BTREngineDownloaderScript": base / "js/desktop/idm-downloader.js",
           "BTREngineGlueScript": base / "js/engine.js"}
parts = ["// Generated by ios/generate-scripts.py; regenerate after any JS change.\n#pragma once\n"]
for name, path in sources.items():
    data = path.read_bytes()
    parts.append(f"// {path.name}: SHA256 {hashlib.sha256(data).hexdigest()}\n")
    # Adjacent C string literals preserve exact UTF-8 JS, including backslashes.
    encoded = data.decode("utf-8")
    parts.append(f"static const char {name}[] =\n")
    for line in encoded.splitlines(keepends=True):
        parts.append(json.dumps(line, ensure_ascii=False) + "\n")
    parts.append(";\n")
(base / "BTRScripts.generated.h").write_text("".join(parts), encoding="utf-8")
